#!/usr/bin/env node
'use strict';
// Regenerate the generated parts of THIRD_PARTY_NOTICES.md:
//
//   node scripts/notices.js                          npm packages (from package-lock.json + node_modules)
//   node scripts/notices.js --herdr-src <checkout>   also herdr's Rust crates, via cargo-about
//
// <checkout> is herdr cloned at the pinned tag, e.g.
//   git clone --depth 1 --branch v0.9.5 https://github.com/herdrdev/herdr /tmp/herdr-src
// cargo-about: cargo install --locked cargo-about --features cli
// Writes scripts/notices/herdr-<version>-crates.tsv (the crate list test/notices.test.js checks).
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const NOTICES = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');
const DIR = path.join(__dirname, 'notices');

function splice(text, name, body) {
  const begin = `<!-- ${name}:begin (generated by scripts/notices.js; do not edit by hand) -->`;
  const end = `<!-- ${name}:end -->`;
  const a = text.indexOf(begin), b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`THIRD_PARTY_NOTICES.md has no ${name} markers`);
  return text.slice(0, a + begin.length) + '\n' + body.trim() + '\n' + text.slice(b);
}

function npmTable() {
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf8'));
  const rows = [];
  for (const [key, meta] of Object.entries(lock.packages)) {
    if (!key || meta.dev) continue;
    const name = key.replace(/^.*node_modules\//, '');
    const pkgFile = path.join(ROOT, key, 'package.json');
    if (!fs.existsSync(pkgFile)) throw new Error(`${key} is not installed; run npm ci first`);
    const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
    if (pkg.version !== meta.version) throw new Error(`${name}: node_modules has ${pkg.version}, lock has ${meta.version}`);
    const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license && pkg.license.type) || 'UNKNOWN';
    const repo = typeof pkg.repository === 'string' ? pkg.repository : (pkg.repository && pkg.repository.url) || '';
    const src = repo.replace(/^git\+/, '').replace(/\.git$/, '')
      .replace(/^(ssh:\/\/)?git@github\.com[:/]/, 'https://github.com/').replace(/^git:\/\//, 'https://')
      .replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1');
    rows.push(`| ${name} | ${meta.version} | ${license} | ${src} |`);
  }
  rows.sort();
  return ['| Package | Version | License | Source |', '|---|---|---|---|', ...rows].join('\n');
}

function herdrCrates(src) {
  const installer = fs.readFileSync(path.join(ROOT, 'install.sh'), 'utf8');
  const pinned = (installer.match(/^HERDR_VERSION="([^"]+)"/m) || [])[1];
  const manifest = path.join(path.resolve(src), 'Cargo.toml');
  const version = (fs.readFileSync(manifest, 'utf8').match(/^version\s*=\s*"([^"]+)"/m) || [])[1];
  if (version !== pinned) throw new Error(`herdr checkout is ${version}, install.sh pins ${pinned}`);
  // Run outside the checkout so its rust-toolchain.toml never triggers a toolchain download.
  const run = (tpl) => execFileSync('cargo', ['about', 'generate', '--locked', '--manifest-path', manifest,
    '-c', path.join(DIR, 'about.toml'), path.join(DIR, tpl)], { cwd: os.tmpdir(), encoding: 'utf8', maxBuffer: 64 << 20 });
  const tsv = run('tsv.hbs').split('\n').filter(Boolean).sort().join('\n') + '\n';
  fs.writeFileSync(path.join(DIR, `herdr-${version}-crates.tsv`), tsv);
  const body = run('about.hbs');
  return { version, count: tsv.trim().split('\n').length, body };
}

const args = process.argv.slice(2);
let text = fs.readFileSync(NOTICES, 'utf8');
text = splice(text, 'npm', npmTable());
const i = args.indexOf('--herdr-src');
if (i >= 0) {
  if (!args[i + 1]) throw new Error('--herdr-src needs a folder');
  const { version, count, body } = herdrCrates(args[i + 1]);
  text = splice(text, 'crates',
    `${count} crates from herdr ${version}'s \`Cargo.lock\` that are built into the release binary ` +
    'for Linux and macOS (x86_64 and arm64), generated with `cargo about`.\n\n' + body);
  console.log(`herdr ${version}: ${count} crates`);
}
fs.writeFileSync(NOTICES, text);
console.log('THIRD_PARTY_NOTICES.md updated');
